class ReviewBotError(Exception):
    """Base class for all bot errors."""


class InvalidSignatureError(ReviewBotError): ...
class DiffParseError(ReviewBotError): ...
class StandardsError(ReviewBotError): ...
class LLMUnavailableError(ReviewBotError): ...
class LLMRateLimitError(ReviewBotError): ...
class LLMInvalidOutputError(ReviewBotError): ...
class GitHubAPIError(ReviewBotError): ...